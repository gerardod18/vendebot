#!/usr/bin/env node
/**
 * Offline fallback for `npx convex codegen`.
 *
 * Writes convex/_generated/{api,server,dataModel}.ts so the project typechecks and tests
 * run in environments that cannot reach a Convex deployment (e.g. sandboxed CI/agents).
 * `npx convex dev` overwrites these files with the real generated code; that's expected.
 *
 * Keep COMPONENTS in sync with convex/convex.config.ts.
 */
import { readdirSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const COMPONENTS = {
  betterAuth: "@convex-dev/better-auth",
  agent: "@convex-dev/agent",
  workflow: "@convex-dev/workflow",
  eventPool: "@convex-dev/workpool",
  rateLimiter: "@convex-dev/rate-limiter",
};

const root = join(process.cwd(), "convex");
const SKIP = new Set(["_generated", "schema.ts", "convex.config.ts", "auth.config.ts", "tsconfig.json"]);

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    if (SKIP.has(name) && dir === root) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (/\.(ts|js)$/.test(name) && !/\.(test|d)\.ts$/.test(name)) out.push(full);
  }
  return out;
}

const modules = walk(root)
  .map((f) => relative(root, f).split(sep).join("/").replace(/\.(ts|js)$/, ""))
  .sort();
const ident = (m) => m.replace(/[^a-zA-Z0-9]/g, "_");

const header = `/* eslint-disable */
/**
 * OFFLINE STUB generated by scripts/gen-convex-stubs.mjs.
 * Replaced by the real output of \`npx convex dev\` / \`npx convex codegen\`.
 */
`;

const api = `${header}
${modules.map((m) => `import type * as ${ident(m)} from "../${m}.js";`).join("\n")}

import type { ApiFromModules, FilterApi, FunctionReference } from "convex/server";
import { anyApi, componentsGeneric } from "convex/server";
${Object.entries(COMPONENTS)
  .map(([n, pkg]) => `import type { ComponentApi as ${n}_api } from "${pkg}/_generated/component.js";`)
  .join("\n")}

declare const fullApi: ApiFromModules<{
${modules.map((m) => `  "${m}": typeof ${ident(m)};`).join("\n")}
}>;

export const api: FilterApi<typeof fullApi, FunctionReference<any, "public">> = anyApi as any;
export const internal: FilterApi<typeof fullApi, FunctionReference<any, "internal">> = anyApi as any;

export const components = componentsGeneric() as unknown as {
${Object.keys(COMPONENTS).map((n) => `  ${n}: ${n}_api<"${n}">;`).join("\n")}
};
`;

const server = `${header}
import type {
  ActionBuilder, HttpActionBuilder, MutationBuilder, QueryBuilder,
  GenericActionCtx, GenericMutationCtx, GenericQueryCtx,
  GenericDatabaseReader, GenericDatabaseWriter,
} from "convex/server";
import {
  actionGeneric, httpActionGeneric, queryGeneric, mutationGeneric,
  internalActionGeneric, internalMutationGeneric, internalQueryGeneric,
} from "convex/server";
import type { DataModel } from "./dataModel.js";

export const query: QueryBuilder<DataModel, "public"> = queryGeneric;
export const internalQuery: QueryBuilder<DataModel, "internal"> = internalQueryGeneric;
export const mutation: MutationBuilder<DataModel, "public"> = mutationGeneric;
export const internalMutation: MutationBuilder<DataModel, "internal"> = internalMutationGeneric;
export const action: ActionBuilder<DataModel, "public"> = actionGeneric;
export const internalAction: ActionBuilder<DataModel, "internal"> = internalActionGeneric;
export const httpAction: HttpActionBuilder = httpActionGeneric;

export type QueryCtx = GenericQueryCtx<DataModel>;
export type MutationCtx = GenericMutationCtx<DataModel>;
export type ActionCtx = GenericActionCtx<DataModel>;
export type DatabaseReader = GenericDatabaseReader<DataModel>;
export type DatabaseWriter = GenericDatabaseWriter<DataModel>;
`;

const dataModel = `${header}
import type { DataModelFromSchemaDefinition, DocumentByName, TableNamesInDataModel, SystemTableNames } from "convex/server";
import type { GenericId } from "convex/values";
import schema from "../schema.js";

export type TableNames = TableNamesInDataModel<DataModel>;
export type Doc<TableName extends TableNames> = DocumentByName<DataModel, TableName>;
export type Id<TableName extends TableNames | SystemTableNames> = GenericId<TableName>;
export type DataModel = DataModelFromSchemaDefinition<typeof schema>;
`;

const out = join(root, "_generated");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "api.ts"), api);
writeFileSync(join(out, "server.ts"), server);
writeFileSync(join(out, "dataModel.ts"), dataModel);
console.log(`wrote convex/_generated (${modules.length} modules, ${Object.keys(COMPONENTS).length} components)`);
